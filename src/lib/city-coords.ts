export function getCityCoords(cityName: string): { lat: number; lng: number; district: string } | null {
  const normalized = cityName.trim().split(/\s+/).map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(" ");
  if (CITY_COORDS[normalized]) return CITY_COORDS[normalized];
  // Try partial matches
  for (const [city, coords] of Object.entries(CITY_COORDS)) {
    if (city.includes(normalized) || normalized.includes(city)) return coords;
  }
  return null;
}
